#!/usr/bin/env python3
"""Generate arm64 forwarding stubs for every function exported by the Discord Social SDK.

The dylib does not link discord_partner_sdk.framework. Each Discord_* symbol used by
discordpp.h is defined here as a tiny trampoline that jumps through a pointer filled in
at run time with dlsym() on whatever copy of the SDK could be dlopen()ed. A tail branch
keeps every argument register untouched, so no prototypes are needed.

This makes Discord work where frameworks cannot be injected (e.g. LiveContainer):
the SDK binary only has to sit next to the tweak dylib.

usage: gen_discord_stubs.py <cdiscord.h> <output.c>
"""
import re
import sys


def main():
    header, out = sys.argv[1], sys.argv[2]
    text = open(header, encoding='utf-8').read()
    names = sorted(set(re.findall(r'DISCORD_API[^;{]*?\b(Discord_[A-Za-z0-9_]+)\s*\(', text)))
    if not names:
        raise SystemExit('no Discord_* functions found in ' + header)

    lines = [
        '// GENERATED by tools/gen_discord_stubs.py - do not edit.',
        '#include <dlfcn.h>',
        '#include <stddef.h>',
        '',
    ]
    for n in names:
        lines.append(f'__attribute__((visibility("hidden"))) void *ivl_dp_{n} = NULL;')
    lines.append('')
    for n in names:
        lines.append(
            f'__asm__(".text\\n.p2align 2\\n.globl _{n}\\n.private_extern _{n}\\n_{n}:\\n'
            f'\\tadrp x16, _ivl_dp_{n}@PAGE\\n\\tldr x16, [x16, _ivl_dp_{n}@PAGEOFF]\\n\\tbr x16\\n");'
        )
    lines += [
        '',
        f'static const char *const kIVLDiscordNames[{len(names)}] = {{',
        *[f'    "{n}",' for n in names],
        '};',
        f'static void **const kIVLDiscordSlots[{len(names)}] = {{',
        *[f'    &ivl_dp_{n},' for n in names],
        '};',
        '',
        '/// Resolves every stub against `handle`. Returns the number of missing symbols (0 = ready).',
        '__attribute__((visibility("hidden"))) int IVLDiscordBindStubs(void *handle) {',
        '    int missing = 0;',
        f'    for (int i = 0; i < {len(names)}; i++) {{',
        '        void *p = dlsym(handle, kIVLDiscordNames[i]);',
        '        if (!p) missing++;',
        '        *kIVLDiscordSlots[i] = p;',
        '    }',
        '    return missing;',
        '}',
        '',
    ]
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print(f'{out}: {len(names)} stubs')


if __name__ == '__main__':
    main()
