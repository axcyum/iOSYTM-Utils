NSString *IVLLoc(NSString *key) {
    static NSDictionary *table, *fallback;
    static dispatch_once_t once;
    dispatch_once(&once, ^{
        NSString *lang = [NSLocale preferredLanguages].firstObject ?: @"en";
        fallback = IVLStringsEN();
        if ([lang hasPrefix:@"ja"]) table = IVLStringsJA();
        else if ([lang hasPrefix:@"ko"]) table = IVLStringsKO();
        else table = fallback;
    });
    return table[key] ?: fallback[key] ?: key;
}
